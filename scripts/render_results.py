VIN_LISTS = ("results", "easyocr_results", "images", "vins")   # primary engine first, then the comparison


def vin_entries(sec: Any) -> list[tuple[str, dict[str, Any]]]:
    """Per-image records of every engine: {file: {...}}, [{file, ...}] or the notebook's
    {results: [...], easyocr_results: [...], <summary fields>}."""
    if isinstance(sec, dict) and not all(isinstance(v, dict) for v in sec.values()):
        items: list[Any] = []
        for k in VIN_LISTS:
            v = sec.get(k)
            items += v if isinstance(v, list) else (
                [{"file": f, **d} for f, d in v.items() if isinstance(d, dict)] if isinstance(v, dict) else [])
        sec = items
    return keyed_entries(sec, ("file", "image", "input", "name", "id"))


def vin_summary(sec: Any) -> dict[str, Any]:
    """Scalar summary fields of the notebook's VIN section (n_images, n_read, ...); {} for other layouts."""
    if isinstance(sec, dict) and not all(isinstance(v, dict) for v in sec.values()):
        return {k: v for k, v in sec.items() if not isinstance(v, (dict, list)) and k not in DROP_VIN_KEYS}
    return {}


