"""Regenerate the generated tables of the smoke-test docs from outputs/smoke/<run>/.

Reads every run directory under outputs/smoke/ (results.json, latency.csv, estimate.csv; env.json,
privacy.json, vin_results.json and detections.csv as fallbacks; missing or broken pieces are tolerated
and reported) and rewrites ONLY the text between "<!-- BEGIN:<name> -->" and "<!-- END:<name> -->" in
  docs/research/smoke_test_results.md  runs_env, models, detections, privacy, vin, latency, estimate, artifacts
  docs/research/model_candidates.md    measured_latency (skipped with a warning if the file/marker is absent)
Everything outside the markers is kept byte for byte. With no run directory at all the docs are left
untouched (outputs/ is gitignored, so a fresh clone must not wipe committed tables).

Determinism: runs and models are sorted, every number is formatted from the run files with one rule per
column name (ms 1 decimal; seconds and load average 2; confidences, scores, IoU and fractions 3; counts as
integers; other floats 2; a nested key inherits its parent's unit, e.g. timings_ms.det is ms), rounded half
up from the recorded decimal value, and nothing time-dependent is written, so --check fails only when the
inputs changed (or a block's markers are broken).
VIN privacy: VINs are shown as stored (masked). As a second line of defence every rendered text has each
12+ character token of the VIN alphabet and each 17-character alphanumeric token with >= 3 digits masked
after its 11th character, OCR corrections that name a character after position 11 are redacted, and raw
OCR text fields are dropped.

Usage:
    python scripts/render_results.py            # rewrite the generated blocks
    python scripts/render_results.py --check    # exit 1 with a diff summary if a rewrite would change a doc
"""

