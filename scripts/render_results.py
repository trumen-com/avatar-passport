# --------------------------------------------------------------------------- markers

def marker_span(text: str, name: str) -> tuple[int, int] | str:
    """(start, end) of the body between the markers, or the reason the block cannot be replaced."""
    begin, end = f"<!-- BEGIN:{name} -->", f"<!-- END:{name} -->"
    nb, ne = text.count(begin), text.count(end)
    if nb == 0 and ne == 0:
        return "markers not found"
    if nb != 1 or ne != 1:
        return f"BEGIN appears {nb}x, END {ne}x"
    i, j = text.index(begin) + len(begin), text.index(end)
    if j < i:
        return "END marker before BEGIN marker"
    if "<!-- BEGIN:" in text[i:j] or "<!-- END:" in text[i:j]:
        return "another marker inside the block"
    return i, j


def replace_blocks(text: str, blocks: dict[str, list[str]], doc: str, skipped: list[str] | None = None) -> str:
    """Replace each block body; text outside the markers is untouched. Blocks whose markers are missing or
    broken are left as they are, warned about and appended to `skipped`."""
    nl = "\r\n" if "\r\n" in text else "\n"
    for name, body in blocks.items():
        span = marker_span(text, name)
        if isinstance(span, str):
            warn(f"{doc}: block '{name}' skipped ({span})")
            if skipped is not None:
                skipped.append(f"{doc}: {name} ({span})")
            continue
        i, j = span
        text = text[:i] + nl + nl.join([GENERATED_NOTE, *body]) + nl + text[j:]
    return text


def block_bodies(text: str, names: Iterable[str]) -> dict[str, str]:
    return {n: text[s[0]:s[1]] for n in names if not isinstance(s := marker_span(text, n), str)}


# --------------------------------------------------------------------------- CLI

def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if regenerating would change a doc (no writes)")
    ap.add_argument("--outputs-dir", type=Path, default=REPO_ROOT / "outputs" / "smoke", help="run directories")
    ap.add_argument("--docs", type=Path, default=REPO_ROOT / "docs" / "research",
                    help=f"directory holding {SMOKE_DOC} and {CANDIDATES_DOC}")
    ap.add_argument("--assets-dir", type=Path, default=None, help="committed copies (default: <docs>/../assets/smoke)")
    return ap.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    smoke = args.docs / SMOKE_DOC
    if not smoke.is_file():
        print(f"[render_results] ERROR: {smoke} not found", file=sys.stderr)
        return 2
    runs = load_runs(args.outputs_dir)
    if not runs:
        warn(f"no run directories under {args.outputs_dir}; docs left untouched")
        return 0
    for r in runs:
        for p in r.problems:
            warn(f"run {r.name}: {p}")
    assets = args.assets_dir or args.docs.parent / "assets" / "smoke"
    targets = [(smoke, render_blocks(runs, args.outputs_dir, assets, smoke.parent))]
    cand = args.docs / CANDIDATES_DOC
    span = marker_span(cand.read_bytes().decode("utf-8"), "measured_latency") if cand.is_file() else "file not found"
    skipped: list[str] = []
    if isinstance(span, str):
        # absent file / markers: another agent owns that file, so only warn; broken markers: G5 cannot pass
        warn(f"{cand}: measured_latency skipped ({span}); another agent writes that file")
        if span not in ("file not found", "markers not found"):
            skipped.append(f"{CANDIDATES_DOC}: measured_latency ({span})")
    else:
        targets.append((cand, {"measured_latency": block_measured_latency(runs, display_dir(args.outputs_dir))}))
    changed = []
    for path, blocks in targets:
        old = path.read_bytes().decode("utf-8")
        new = replace_blocks(old, blocks, path.name, skipped)
        if new != old:
            changed.append((path, old, new, list(blocks)))
    names = ", ".join(r.name for r in runs)
    if args.check:
        if skipped:
            print(f"[render_results] NOT GENERATED (fix the markers): {'; '.join(skipped)}")
        if not changed:
            if skipped:
                return 1
            print(f"[render_results] up to date (runs: {names})")
            return 0
        for path, old, new, blocks in changed:
            ob, nb = block_bodies(old, blocks), block_bodies(new, blocks)
            print(f"[render_results] STALE {path}: blocks {', '.join(b for b in blocks if ob.get(b) != nb.get(b))}")
            diff = list(difflib.unified_diff(old.splitlines(), new.splitlines(), str(path), "regenerated", n=0,
                                             lineterm=""))
            for line in diff[:60]:
                print("    " + line)
            if len(diff) > 60:
                print(f"    ... {len(diff) - 60} more diff lines")
        print("[render_results] regenerate with: python scripts/render_results.py")
        return 1
    for path, _, new, _ in changed:
        path.write_bytes(new.encode("utf-8"))
    print(f"[render_results] runs: {names}; updated: {', '.join(p.name for p, *_ in changed) or 'nothing (up to date)'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
