def privacy_from_side(side: Any) -> dict[str, Any] | None:
    """Totals computed from privacy.json (per-input records with ok / n_plates / n_faces / passes)."""
    if isinstance(side, dict) and not all(isinstance(v, dict) for v in side.values()):
        side = side.get("inputs") or side.get("per_input") or side.get("items")
    items = list(side.values()) if isinstance(side, dict) else side
    if not isinstance(items, list) or not items or not all(isinstance(x, dict) for x in items):
        return None
    out: dict[str, Any] = {"inputs": len(items), "ok": 0, "dropped": 0, "n_plates": 0, "n_faces": 0}
    passes: dict[str, int] = {}
    for it in items:
        out["ok" if parse_cell("ok", it.get("ok")) is True else "dropped"] += 1
        out["n_plates"] += int(num(it.get("n_plates")) or 0)
        out["n_faces"] += int(num(it.get("n_faces")) or 0)
        for k, v in (it.get("passes") or {}).items():
            passes[str(k)] = passes.get(str(k), 0) + int(num(v) or 0)
    if passes:
        out["passes"] = passes
    out["source"] = "privacy.json (computed)"
    return out


