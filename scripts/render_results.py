# --------------------------------------------------------------------------- formatting

def natural_key(s: str) -> tuple[Any, ...]:
    """Sort key: 'R2' < 'R10'; ties broken by the exact string so the order is total."""
    return tuple((0, int(t)) if t.isdigit() else (1, t.lower()) for t in re.split(r"(\d+)", s) if t) + ((2, s),)


def warn(msg: str) -> None:
    print(f"[render_results] WARNING: {msg}", file=sys.stderr)


def mask_vin_like(text: str) -> str:
    """Mask the tail of anything that could be a VIN (12+ VIN-alphabet chars, or any 17 alphanumerics, with
    >= 3 digits) and redact OCR corrections that reveal a character after position 11."""
    def repl(m: re.Match[str]) -> str:
        tok = m.group(0)
        return tok if sum(c.isdigit() for c in tok) < 3 else tok[:VIN_SHOWN] + "*" * (len(tok) - VIN_SHOWN)

    def tail(m: re.Match[str]) -> str:
        return m.group(0) if int(m.group(1)) <= VIN_SHOWN else f"pos {m.group(1)}: *->*"
    return TAIL_FIX.sub(tail, TOKEN_17.sub(repl, VIN_LIKE.sub(repl, text)))


def scrub_paths(text: str) -> str:
    root = str(REPO_ROOT)
    text = text.replace(root + os.sep, "").replace(root, ".")
    home = str(Path.home())
    return text.replace(home, "~") if len(home) > 1 else text


def md_escape(text: str) -> str:
    """One line; VIN-like tokens masked; pipes escaped; '<' escaped where it could open an HTML tag; masked
    VINs as code."""
    text = mask_vin_like(" ".join(str(text).split())).replace("|", "\\|")
    text = re.sub(r"<(?=[A-Za-z/!?])", "&lt;", text)
    return MASKED_TOKEN.sub(r"`\1`", text)


def num(v: Any) -> float | int | None:
    """int/float from a number or numeric string; None for anything else (bool, NaN, text)."""
    if isinstance(v, bool) or v is None:
        return None
    if isinstance(v, (int, float)):
        return None if isinstance(v, float) and math.isnan(v) else v
    if isinstance(v, str):
        s = v.strip()
        try:
            return int(s)
        except ValueError:
            pass
        try:
            f = float(s)
        except ValueError:
            return None
        return None if math.isnan(f) else f
    return None


def parse_cell(key: str, v: Any) -> Any:
    """CSV string -> None / bool / int / float / str (JSON-typed values pass through unchanged)."""
    if not isinstance(v, str):
        return v
    s = v.strip()
    low = s.lower()
    if s == "" or low in {"nan", "none", "null"}:
        return None
    if key in TEXT_KEYS:
        return s
    if low in {"true", "false"} or (key in BOOL_KEYS and low in {"0", "1", "yes", "no"}):
        return low in {"true", "1", "yes"}
    n = num(s)
    return s if n is None else n


def unit_of(segment: str) -> str | None:
    """Unit implied by one key segment ('median_ms' -> ms), or None."""
    s = segment.lower()
    if s.endswith("_ms") or MS_TOKEN.search(s):
        return "ms"
    if s.endswith("_s") or s in {"s", "seconds"} or "loadavg" in s:
        return "s"
    if any(t in s for t in ("conf", "score", "frac", "ratio", "iou")):
        return "fraction"
    if s.endswith(("_mb", "_gb", "_kb")):
        return "size"
    return None


def fixed(x: float | int, nd: int) -> str:
    """x with nd decimals, rounded half up from its shortest decimal repr (500.25 -> 500.3, as read in the CSV)."""
    try:
        d = decimal.Decimal(repr(float(x)) if isinstance(x, float) else int(x))
        return f"{d.quantize(decimal.Decimal(1).scaleb(-nd), rounding=decimal.ROUND_HALF_UP):f}"
    except (decimal.InvalidOperation, ValueError):
        return f"{x:.{nd}f}"


def fmt_number(key: str, x: float | int) -> str:
    """One formatting rule per column name, so a column never mixes precisions. The last dotted segment with
    a unit wins (timings_ms.det is ms)."""
    unit = next((u for seg in reversed(key.split(".")) if (u := unit_of(seg))), None)
    if unit is not None:
        return fixed(x, UNIT_DECIMALS[unit])
    if isinstance(x, int) or float(x).is_integer():
        return str(int(x))
    return fixed(x, 2)


def plain(key: str, v: Any) -> str:
    """Typed value -> text (numbers by column rule, bools yes/no, dicts/lists joined)."""
    if v is None:
        return ""
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, (int, float)):
        if isinstance(v, float) and (math.isnan(v) or math.isinf(v)):
            return "" if math.isnan(v) else str(v)
        return fmt_number(key, v)
    if isinstance(v, str):
        s = v.strip()
        return s[:12] if "sha256" in key.lower() and re.fullmatch(r"[0-9a-fA-F]{64}", s) else s
    if isinstance(v, dict):
        items = sorted(v.items(), key=lambda kv: natural_key(str(kv[0])))
        text = ", ".join(f"{k}: {plain(f'{key}.{k}', x)}" for k, x in items[:LIST_LIMIT])
        return text + (f", ... (+{len(items) - LIST_LIMIT} more)" if len(items) > LIST_LIMIT else "")
    if isinstance(v, (list, tuple)):
        if any(isinstance(x, (dict, list, tuple)) for x in v):
            return f"{len(v)} entries"
        text = ", ".join(plain(key, x) for x in v[:LIST_LIMIT])
        return text + (f", ... (+{len(v) - LIST_LIMIT} more)" if len(v) > LIST_LIMIT else "")
    return str(v)


def cell(key: str, v: Any) -> str:
    """Escaped, path-scrubbed, VIN-masked markdown cell text."""
    return md_escape(mask_vin_like(scrub_paths(plain(key, v))))


def short(text: Any, n: int = ERROR_CHARS) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= n else text[: n - 1] + "…"


def flatten(obj: Any, prefix: str = "", *, drop: Iterable[str] = ()) -> dict[str, Any]:
    """Nested dicts -> dotted keys (lists stay values); keys in `drop` are removed at any depth."""
    drop = set(drop)
    if isinstance(obj, dict):
        out: dict[str, Any] = {}
        for k, v in obj.items():
            if str(k) not in drop:
                out.update(flatten(v, f"{prefix}.{k}" if prefix else str(k), drop=drop))
        return out
    return {prefix or "value": obj}


def ordered_keys(keys: Iterable[str], preferred: Sequence[str]) -> list[str]:
    ks = list(dict.fromkeys(keys))
    first = [p for p in preferred if p in ks]
    return first + sorted((k for k in ks if k not in first), key=natural_key)


def md_table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    """Markdown table; columns whose non-empty cells are all plain numbers are right-aligned."""
    align = []
    for i in range(len(header)):
        vals = [r[i] for r in rows if r[i] != ""]
        align.append("---:" if vals and all(re.fullmatch(r"-?\d+(\.\d+)?", v) for v in vals) else "---")
    out = ["| " + " | ".join(md_escape(h) for h in header) + " |", "| " + " | ".join(align) + " |"]
    return out + ["| " + " | ".join(r) + " |" for r in rows]


def keyed_entries(section: Any, id_keys: Sequence[str] = ("key", "model", "model_key", "name", "id")
                  ) -> list[tuple[str, dict[str, Any]]]:
    """{id: {...}} or [{id_key: id, ...}] -> [(id, fields)] (non-dict entries ignored)."""
    if isinstance(section, dict):
        return [(str(k), v) for k, v in section.items() if isinstance(v, dict)]
    out: list[tuple[str, dict[str, Any]]] = []
    if isinstance(section, list):
        for i, item in enumerate(section):
            if isinstance(item, dict):
                idk = next((k for k in id_keys if isinstance(item.get(k), (str, int))), None)
                out.append((str(item[idk]) if idk else f"#{i + 1}", {k: v for k, v in item.items() if k != idk}))
    return out


# --------------------------------------------------------------------------- loading

@dataclass
class Run:
    name: str
    path: Path
    results: dict[str, Any] = field(default_factory=dict)
    has_results: bool = False
    side: dict[str, Any] = field(default_factory=dict)          # env.json / privacy.json / vin_results.json
    latency: list[dict[str, Any]] = field(default_factory=list)
    latency_src: str = ""
    estimate: list[dict[str, Any]] = field(default_factory=list)
    estimate_cols: list[str] = field(default_factory=list)
    estimate_src: str = ""
    detections_csv: list[dict[str, str]] = field(default_factory=list)
    problems: list[str] = field(default_factory=list)

    def section(self, *keys: str) -> Any:
        for k in keys:
            if self.results.get(k) not in (None, {}, []):
                return self.results[k]
        return None


def read_csv(path: Path) -> tuple[list[str], list[dict[str, str]]]:
    with path.open(newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        cols = [c.strip() for c in (reader.fieldnames or []) if c is not None]
        rows = [{k.strip(): (v or "").strip() for k, v in raw.items() if k is not None and not isinstance(v, list)}
                for raw in reader]
    return cols, rows


def load_run(d: Path) -> Run:
    """Read everything once, so every unreadable file is known before rendering starts."""
    run = Run(d.name, d)
    p = d / "results.json"
    if p.is_file():
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
            if isinstance(data, dict):
                run.results, run.has_results = data, True
            else:
                run.problems.append("results.json: top level is not an object")
        except (OSError, ValueError) as exc:
            run.problems.append(f"results.json: {short(exc, 100)}")
    for name in SIDE_JSON:
        p = d / name
        if p.is_file():
            try:
                run.side[name] = json.loads(p.read_text(encoding="utf-8"))
            except (OSError, ValueError) as exc:
                run.problems.append(f"{name}: {short(exc, 100)}")
    for name, attr in (("latency.csv", "latency"), ("estimate.csv", "estimate")):
        p = d / name
        if p.is_file():
            try:
                cols, rows = read_csv(p)
            except (OSError, csv.Error, UnicodeDecodeError) as exc:
                run.problems.append(f"{name}: {short(exc, 100)}")
                continue
            setattr(run, attr, rows)
            setattr(run, f"{attr}_src", name)
            if attr == "estimate":
                run.estimate_cols = cols
        elif isinstance(run.results.get(attr), list) and run.results[attr]:
            rows = [r for r in run.results[attr] if isinstance(r, dict)]
            setattr(run, attr, rows)
            setattr(run, f"{attr}_src", f"results.json ({attr})")
            if attr == "estimate":
                run.estimate_cols = list(dict.fromkeys(k for r in rows for k in r))
    p = d / "detections.csv"
    if p.is_file():
        try:
            run.detections_csv = read_csv(p)[1]
        except (OSError, csv.Error, UnicodeDecodeError) as exc:
            run.problems.append(f"detections.csv: {short(exc, 100)}")
    return run


def load_runs(outputs_dir: Path) -> list[Run]:
    """Every subdirectory holding at least one known run file, in natural order of its name (= run id)."""
    if not outputs_dir.is_dir():
        return []
    dirs = [p for p in outputs_dir.iterdir() if p.is_dir() and any((p / f).is_file() for f in RUN_MARKER_FILES)]
    return [load_run(d) for d in sorted(dirs, key=lambda p: natural_key(p.name))]


# --------------------------------------------------------------------------- blocks

def display_dir(outputs_dir: Path) -> str:
    try:
        return outputs_dir.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return scrub_paths(outputs_dir.as_posix())


def caption(runs: Iterable[str], source: str) -> str:
    ids = ", ".join(dict.fromkeys(runs)) or "none"
    return f"_measured: {md_escape(mask_vin_like(ids))}, source_ `{source}`"


def no_data(what: str, out_dir: str) -> list[str]:
    return [f"_no data yet: no run under `{out_dir}/` has {what}._"]


def transposed(columns: list[tuple[str, dict[str, Any]]], preferred: Sequence[str], first: str = "field") -> list[str]:
    """One row per key, one column per record (runs side by side)."""
    keys = ordered_keys((k for _, d in columns for k in d), preferred)
    rows = [[md_escape(k)] + [cell(k, d.get(k)) for _, d in columns] for k in keys]
    return md_table([first] + [c for c, _ in columns], rows)


def error_text(e: Any) -> str:
    """One recorded error: 'stage: message (context)' for the notebook's {stage, ..., error} records."""
    if isinstance(e, dict) and "error" in e:
        ctx = ", ".join(f"{k}={plain(str(k), v)}" for k, v in sorted(e.items(), key=lambda kv: natural_key(str(kv[0])))
                        if k not in ("stage", "error"))
        return f"{plain('stage', e.get('stage')) or '?'}: {plain('error', e['error'])}" + (f" ({ctx})" if ctx else "")
    return plain("error", e)


def block_runs_env(runs: list[Run], out_dir: str) -> list[str]:
    status = []
    for r in runs:
        errs = r.section("errors")
        errs = errs if isinstance(errs, list) else ([errs] if errs else [])
        first = "; ".join(short(error_text(e), 80) for e in errs[:3]) + (" ..." if len(errs) > 3 else "")
        status.append([md_escape(r.name), "yes" if r.has_results else "no", str(len(r.latency)), str(len(r.estimate)),
                       str(len(errs)), cell("error", first), cell("problems", "; ".join(r.problems))])
    lines = ["Run status:", ""]
    lines += md_table(["run", "results.json", "latency rows", "estimate rows", "errors", "first errors",
                       "unreadable files"], status)
    lines += ["", caption((r.name for r in runs), f"{out_dir}/<run>/"), ""]
    envs = []
    for r in runs:
        env, src = r.section("env", "environment"), "results.json"
        if not isinstance(env, dict):
            env, src = r.side.get("env.json"), "env.json"
        if isinstance(env, dict):
            envs.append((r.name, src, flatten(env)))
    if not envs:
        return lines + no_data("an environment record (results.json `env` or env.json)", out_dir)
    preferred = ("platform", "colab", "versions.python", "versions.torch", "versions.torchvision",
                 "versions.ultralytics", "versions.onnxruntime", "versions.cv2", "versions.numpy", "versions.rapidocr",
                 "gpu.device", "gpu.cuda_available", "gpu.name", "gpu.capability", "gpu.arch_supported",
                 "gpu.torch_cuda", "gpu.driver", "gpu.memory_gb", "cpu.model", "cpu.count", "cpu.loadavg",
                 "cpu.power_profile", "cpu.mem_total", "cpu.torch_threads",
                 "python", "os", "cpu", "cpu_model", "cpu_count", "loadavg", "power_profile", "gpu", "gpu_name",
                 "capability", "cuda", "cuda_available", "torch", "torchvision", "ultralytics", "onnxruntime", "cv2",
                 "opencv", "numpy", "rapidocr")
    lines += ["Hardware and software:", ""]
    lines += transposed([(n, d) for n, _, d in envs], preferred)
    srcs = " or ".join(sorted({s for _, s, _ in envs}))
    lines += ["", caption((n for n, _, _ in envs), f"{out_dir}/<run>/{srcs}") + " (`env`)"]
    return lines


def block_models(runs: list[Run], out_dir: str) -> list[str]:
    rows = [(r.name, key, info) for r in runs for key, info in keyed_entries(r.section("models"))]
    if not rows:
        return no_data("a `models` section in results.json", out_dir)
    rows.sort(key=lambda t: (natural_key(t[0]), natural_key(t[1])))
    preferred = ("status", "role", "task", "imgsz", "conf", "iou", "n_classes", "size", "size_bytes", "size_mb",
                 "sha256", "path", "file", "load_ms", "error")
    table_rows, names_seen = [], {}
    for run, key, info in rows:
        names = info.get("names")
        d = {k: v for k, v in info.items() if k != "names"}
        if isinstance(names, (dict, list)) and names:
            d.setdefault("n_classes", len(names))
            pairs = names.items() if isinstance(names, dict) else enumerate(names)
            text = ", ".join(f"{k} {v}" for k, v in sorted(pairs, key=lambda kv: natural_key(str(kv[0]))))
            names_seen.setdefault((key, text), []).append(run)
        table_rows.append((run, key, d))
    cols = ordered_keys((k for _, _, d in table_rows for k in d), preferred)
    lines = md_table(["run", "model"] + cols,
                     [[md_escape(run), md_escape(key)] + [cell(c, d.get(c)) for c in cols] for run, key, d in table_rows])
    lines += ["", caption((r for r, _, _ in rows), f"{out_dir}/<run>/results.json")
              + " (`models`); sha256 shows the first 12 hex chars"]
    if names_seen:
        lines += ["", "Runtime class names (`model.names`, index name):", ""]
        for (key, text), rs in sorted(names_seen.items(), key=lambda kv: (natural_key(kv[0][0]), kv[0][1])):
            lines.append(f"- `{key}` ({md_escape(', '.join(rs))}): {md_escape(mask_vin_like(scrub_paths(text)))}")
    return lines


def detections_from_csv(rows: list[dict[str, str]]) -> list[tuple[str, dict[str, Any]]]:
    """Per-model counts computed from detections.csv (one row per detection)."""
    per: dict[str, dict[str, Any]] = {}
    for row in rows:
        d = per.setdefault(row.get("model", ""), {"inputs": set(), "detections": 0, "per_class": {}, "confs": []})
        d["inputs"].add(row.get("input", ""))
        d["detections"] += 1
        cls = row.get("class_name") or "?"
        d["per_class"][cls] = d["per_class"].get(cls, 0) + 1
        c = num(row.get("conf"))
        if c is not None:
            d["confs"].append(float(c))
    return [(m, {"inputs_with_detections": len(d["inputs"]), "detections": d["detections"],
                 "mean_conf": sum(d["confs"]) / len(d["confs"]) if d["confs"] else None,
                 "per_class": d["per_class"], "source": "detections.csv (computed)"}) for m, d in per.items()]


def block_detections(runs: list[Run], out_dir: str) -> list[str]:
    lines: list[str] = []
    inputs = []
    for r in runs:
        d: dict[str, Any] = {}
        for prefix, sec in (("counts", r.section("counts")), ("quality", r.section("quality", "quality_summary"))):
            if isinstance(sec, dict):
                d.update(flatten(sec, prefix))
        if d:
            inputs.append((r.name, d))
    if inputs:
        lines += ["Inputs and frame quality filter (uncalibrated default thresholds):", ""]
        lines += transposed(inputs, ())
        lines += ["", caption((n for n, _ in inputs), f"{out_dir}/<run>/results.json") + " (`counts`, `quality`)", ""]
    rows: list[tuple[str, str, dict[str, Any]]] = []
    for r in runs:
        entries = keyed_entries(r.section("detections", "detection_summary", "detections_summary", "per_model"))
        rows += [(r.name, m, d) for m, d in (entries or detections_from_csv(r.detections_csv))]
    if not rows:
        return lines + no_data("a per-model detection summary (results.json `detections` or detections.csv)", out_dir)
    rows.sort(key=lambda t: (natural_key(t[0]), natural_key(t[1])))
    preferred = ("inputs", "n_inputs", "frames", "photos", "inputs_with_detections", "detections", "n_detections",
                 "mean_conf", "per_class", "max_mem_mb", "cuda_max_mem_mb", "error", "source")
    cols = ordered_keys((k for _, _, d in rows for k in d), preferred)
